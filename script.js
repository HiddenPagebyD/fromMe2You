// POP-UP FOR LETTERS, MEMORIES & INTERACTIVE BOOK
// ==========================================
function openDetail(item, category) {
  lastFocusedElement = document.activeElement;

  modalEyebrow.textContent = category;
  modalTitle.textContent = item.title;
  modalBody.replaceChildren();

  // 1. If this is the INTERACTIVE BOOK ("One of Our Eras")
  if (item.isBook || item.title === "One of our eras") {
    const bookContainer = document.createElement("div");
    bookContainer.className = "book-container";

    const bookCard = document.createElement("div");
    bookCard.className = "book-card";

    // Bookmark ribbon
    const ribbon = document.createElement("div");
    ribbon.className = "book-ribbon";
    bookCard.appendChild(ribbon);

    // BLANK FRONT PAGE
    const blankPage = document.createElement("div");
    blankPage.className = "book-page-blank";

    const watermark = document.createElement("div");
    watermark.className = "blank-watermark";
    watermark.textContent = "✿";

    const cue = document.createElement("div");
    cue.className = "blank-cue";
    cue.textContent = "a chapter waiting to be read...";

    const turnBtn = document.createElement("button");
    turnBtn.type = "button";
    turnBtn.className = "turn-page-btn";
    turnBtn.innerHTML = 'turn the page <span>↷</span>';

    blankPage.append(watermark, cue, turnBtn);

    // REVEALED PAGE (with message)
    const revealedPage = document.createElement("div");
    revealedPage.className = "book-page-revealed";

    const headerLine = document.createElement("div");
    headerLine.className = "book-header-line";
    headerLine.innerHTML = '<span>Page II • Our Story</span><span>✿</span>';

    const messageText = document.createElement("div");
    messageText.className = "book-revealed-text";
    messageText.textContent = item.message;

    const turnBackBar = document.createElement("div");
    turnBackBar.className = "book-turn-back-bar";

    const turnBackBtn = document.createElement("button");
    turnBackBtn.type = "button";
    turnBackBtn.className = "turn-back-btn";
    turnBackBtn.textContent = "↶ turn back to blank page";

    const footerNote = document.createElement("span");
    footerNote.className = "book-footer-note";
    footerNote.textContent = "kept in heart ♡";

    turnBackBar.append(turnBackBtn, footerNote);
    revealedPage.append(headerLine, messageText, turnBackBar);

    bookCard.append(blankPage, revealedPage);
    bookContainer.appendChild(bookCard);
    modalBody.appendChild(bookContainer);

    // Page-turn animation logic
    turnBtn.addEventListener("click", () => {
      bookCard.classList.add("flipping");
      setTimeout(() => {
        blankPage.style.display = "none";
        revealedPage.classList.add("active");
        bookCard.classList.remove("flipping");
      }, 400);
    });

    turnBackBtn.addEventListener("click", () => {
      bookCard.classList.add("flipping");
      setTimeout(() => {
        revealedPage.classList.remove("active");
        blankPage.style.display = "flex";
        bookCard.classList.remove("flipping");
      }, 400);
    });
  } 
  // 2. Normal text and optional photo gallery (e.g., "The conversation")
  else {
    const textDiv = document.createElement("div");
    textDiv.textContent = item.message;
    modalBody.appendChild(textDiv);

    if (item.images && item.images.length > 0) {
      const gallery = document.createElement("div");
      gallery.className = "modal-gallery";

      item.images.forEach(src => {
        const figure = document.createElement("figure");
        figure.className = "modal-photo-item";

        const img = document.createElement("img");
        img.src = src;
        img.alt = item.title;
        img.loading = "lazy";
        img.onerror = () => { figure.style.display = "none"; };

        figure.appendChild(img);
        gallery.appendChild(figure);
      });

      modalBody.appendChild(gallery);
    }
  }

  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";

  closeModalButton.focus();
}

function closeDetail() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";

  if (lastFocusedElement) {
    lastFocusedElement.focus();
  }
}


// ==========================================
// PLAY VIDEO FULL-SCREEN & MUTE BACKGROUND MUSIC
// ==========================================
function playFullscreenVideo() {
  if (!videoOverlay || !fullscreenVideo) return;

  if (backgroundMusic && !backgroundMusic.paused) {
    wasMusicPlayingBeforeVideo = true;
    backgroundMusic.pause();
  } else {
    wasMusicPlayingBeforeVideo = false;
  }

  videoOverlay.classList.add("active");
  videoOverlay.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";

  fullscreenVideo.currentTime = 0;
  fullscreenVideo.muted = false;
  fullscreenVideo.volume = 1;

  if (fullscreenVideo.requestFullscreen) {
    fullscreenVideo.requestFullscreen().catch(() => {});
  } else if (fullscreenVideo.webkitRequestFullscreen) {
    fullscreenVideo.webkitRequestFullscreen().catch(() => {});
  } else if (fullscreenVideo.webkitEnterFullscreen) {
    fullscreenVideo.webkitEnterFullscreen(); // iPhone iOS
  }

  fullscreenVideo.play().catch(error => {
    console.warn("Video playback note:", error);
  });
}

function stopAndCloseVideo() {
  if (!videoOverlay || !fullscreenVideo) return;

  fullscreenVideo.pause();

  videoOverlay.classList.remove("active");
  videoOverlay.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";

  if (document.fullscreenElement && document.exitFullscreen) {
    document.exitFullscreen().catch(() => {});
  } else if (document.webkitFullscreenElement && document.webkitExitFullscreen) {
    document.webkitExitFullscreen().catch(() => {});
  }

  if (wasMusicPlayingBeforeVideo && backgroundMusic) {
    backgroundMusic.play().catch(error => {
      console.error("Could not resume background music:", error);
    });
  }
}

if (closeVideoBtn) {
  closeVideoBtn.addEventListener("click", stopAndCloseVideo);
}

if (fullscreenVideo) {
  fullscreenVideo.addEventListener("ended", stopAndCloseVideo);
  fullscreenVideo.addEventListener("webkitendfullscreen", stopAndCloseVideo);
}

document.addEventListener("fullscreenchange", () => {
  if (!document.fullscreenElement && videoOverlay && videoOverlay.classList.contains("active")) {
    stopAndCloseVideo();
  }
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape" && videoOverlay && videoOverlay.classList.contains("active")) {
    stopAndCloseVideo();
  }
});


