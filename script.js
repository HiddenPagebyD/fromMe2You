// NAVIGATION (Pages & Home)
// ==========================================
function openPage(pageName) {
  document.querySelector(".letter-section").style.display = "none";
  document.querySelector(".explore-section").style.display = "none";

  document.querySelectorAll(".content-page").forEach(page => {
    page.classList.remove("active");
  });

  const selectedPage = document.getElementById("page-" + pageName);
  if (selectedPage) {
    selectedPage.classList.add("active");
  }

  window.scrollTo({ top: 0, behavior: "smooth" });
}

function goHome() {
  document.querySelector(".letter-section").style.display = "";
  document.querySelector(".explore-section").style.display = "";

  document.querySelectorAll(".content-page").forEach(page => {
    page.classList.remove("active");
  });

  window.scrollTo({ top: 0, behavior: "smooth" });
}

document.querySelectorAll(".section-link").forEach(button => {
  button.addEventListener("click", () => {
    openPage(button.dataset.page);
  });
});

document.querySelectorAll("[data-home]").forEach(button => {
  button.addEventListener("click", goHome);
});


