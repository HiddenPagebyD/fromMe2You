function createItemCard(item, category) {
  const card = document.createElement("button");
  card.type = "button";
  card.className = "item-card";

  const symbol = document.createElement("span");
  symbol.className = "item-symbol";
  symbol.textContent = item.icon;

  const title = document.createElement("h3");
  title.textContent = item.title;

  const preview = document.createElement("p");
  preview.textContent = item.preview;

  card.append(symbol, title, preview);

  card.addEventListener("click", () => {
    if (item.isVideo || item.title === "A photo worth keeping") {
      playFullscreenVideo();
    } else {
      openDetail(item, category);
    }
  });

  return card;
}

function renderItems(container, items, category) {
  container.replaceChildren();
  items.forEach(item => {
    container.appendChild(createItemCard(item, category));
  });
}

function renderSongs() {
  songList.replaceChildren();

  songs.forEach(song => {
    const link = document.createElement("a");
    link.className = "song";
    link.href = song.url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";

    const art = document.createElement("span");
    art.className = "song-art";
    art.textContent = "♫";
    art.setAttribute("aria-hidden", "true");

    const info = document.createElement("span");
    info.className = "song-info";

    const title = document.createElement("strong");
    title.textContent = song.title;

    const artist = document.createElement("span");
    artist.textContent = song.artist;

    const note = document.createElement("span");
    note.textContent = song.note;

    info.append(title, artist, note);

    const arrow = document.createElement("span");
    arrow.className = "song-play";
    arrow.textContent = "↗";
    arrow.setAttribute("aria-hidden", "true");

    link.append(art, info, arrow);
    songList.appendChild(link);
  });
}


