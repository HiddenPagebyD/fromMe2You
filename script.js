// BACKGROUND MUSIC TOGGLE
// ==========================================
const backgroundMusic = document.getElementById("backgroundMusic");
const musicToggle = document.getElementById("musicToggle");

function updateMusicLabel() {
  if (!musicToggle || !backgroundMusic) return;
  musicToggle.textContent = backgroundMusic.paused
    ? "♡ Play this banger"
    : "♫ Pause this banger";
}

if (backgroundMusic && musicToggle) {
  backgroundMusic.addEventListener("play", updateMusicLabel);
  backgroundMusic.addEventListener("pause", updateMusicLabel);

  musicToggle.addEventListener("click", () => {
    if (backgroundMusic.paused) {
      backgroundMusic.play().catch(error => console.error("Music error:", error));
    } else {
      backgroundMusic.pause();
    }
  });

  updateMusicLabel();
}


